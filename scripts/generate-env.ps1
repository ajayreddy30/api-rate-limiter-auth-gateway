# Creates .env with strong random secrets (Windows PowerShell 5.1+ / PowerShell 7).
# Refuses to overwrite an existing .env. The file is git-ignored - never commit it.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'

if (Test-Path $envFile) {
    Write-Host ".env already exists - not overwriting. Delete it first if you really want new secrets." -ForegroundColor Yellow
    exit 1
}

function New-Secret([int]$bytes) {
    $buf = New-Object byte[] $bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($buf)
    $rng.Dispose()
    # URL-safe base64 without padding: only A-Z a-z 0-9 - _  (safe in .env files and shells)
    return ([Convert]::ToBase64String($buf)).Replace('+', '-').Replace('/', '_').TrimEnd('=')
}

$adminPassword = (New-Secret 18) + 'A9'   # suffix guarantees at least one letter and one digit

$lines = @(
    '# Generated by scripts/generate-env.ps1 - NEVER commit this file.',
    "JWT_SECRET=$(New-Secret 48)",
    "INTERNAL_API_KEY=$(New-Secret 48)",
    "REDIS_PASSWORD=$(New-Secret 32)",
    "AUTH_DB_PASSWORD=$(New-Secret 32)",
    "PRODUCT_DB_PASSWORD=$(New-Secret 32)",
    'AUTH_DB_NAME=authdb',
    'AUTH_DB_USER=auth_user',
    'PRODUCT_DB_NAME=productdb',
    'PRODUCT_DB_USER=product_user',
    'JWT_ISSUER=api-gateway-auth',
    'JWT_AUDIENCE=api-gateway',
    'JWT_EXPIRATION_MINUTES=15',
    'REQUIRE_HTTPS=false',
    'TRUSTED_PROXY_HOPS=0',
    'CORS_ALLOWED_ORIGINS=',
    'BOOTSTRAP_ADMIN_USERNAME=admin',
    "BOOTSTRAP_ADMIN_PASSWORD=$adminPassword",
    'DOMAIN=localhost'
)

# UTF-8 without BOM (a BOM would corrupt the first key for docker compose).
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($envFile, ($lines -join "`n") + "`n", $utf8NoBom)

Write-Host "Created $envFile" -ForegroundColor Green
Write-Host "First admin login -> username: admin   password: $adminPassword"
Write-Host "Save that password in a password manager, then delete the two BOOTSTRAP_ADMIN_* lines from .env after the first start."
